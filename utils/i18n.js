export function useTranslation() {
  const { currentLanguage } = useLanguage();

  return useMemo(() => ({
    t: (key) => translations[currentLanguage]?.[key] ?? translations.en[key] ?? key,
    currentLanguage
  }), [currentLanguage]);
}
